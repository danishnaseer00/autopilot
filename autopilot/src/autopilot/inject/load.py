"""Locust load profiles (SPEC-30 R-10/R-11, Q-4).

The harness records the load profile with every injection and asserts that load
actually reached the application before injecting.  Profiles are generated from
the fixed application catalogue and a per-run seed, so the exact user count,
spawn rate and duration are reproducible.  ``locustfile.py`` is rendered as
source text; importing Locust is not required to build or test a plan.
"""

from __future__ import annotations

import random
import re
from dataclasses import dataclass
from typing import Any

from autopilot.inject.errors import ParameterError
from autopilot.inject.testapps import TestApplication

DEFAULT_MIN_RPS = 1.0


@dataclass(frozen=True)
class LoadEndpoint:
    path: str
    weight: int
    service: str

    def __post_init__(self) -> None:
        if not isinstance(self.path, str) or not self.path.startswith("/"):
            raise ParameterError(f"load endpoint path {self.path!r} must start with /")
        if not isinstance(self.weight, int) or isinstance(self.weight, bool) or self.weight < 1:
            raise ParameterError(f"load endpoint {self.path!r} needs a positive weight")
        if not isinstance(self.service, str) or not self.service:
            raise ParameterError(f"load endpoint {self.path!r} needs a service")

    def to_dict(self) -> dict[str, Any]:
        return {"path": self.path, "weight": self.weight, "service": self.service}


@dataclass(frozen=True)
class LoadProfile:
    vusers: int
    spawn_rate: float
    duration_s: int
    host: str
    endpoints: tuple[LoadEndpoint, ...]
    min_rps: float
    seed: int

    def __post_init__(self) -> None:
        if not isinstance(self.vusers, int) or isinstance(self.vusers, bool) or self.vusers < 1:
            raise ParameterError("load vusers must be a positive integer")
        if not isinstance(self.spawn_rate, (int, float)) or isinstance(self.spawn_rate, bool):
            raise ParameterError("load spawn_rate must be numeric")
        if float(self.spawn_rate) <= 0:
            raise ParameterError("load spawn_rate must be positive")
        if not isinstance(self.duration_s, int) or isinstance(self.duration_s, bool) or self.duration_s < 1:
            raise ParameterError("load duration_s must be a positive integer")
        if not isinstance(self.host, str) or not self.host.startswith(("http://", "https://")):
            raise ParameterError("load host must be an http(s) URL")
        if not self.endpoints:
            raise ParameterError("load profile needs at least one endpoint")
        if not isinstance(self.min_rps, (int, float)) or isinstance(self.min_rps, bool):
            raise ParameterError("load min_rps must be numeric")
        if float(self.min_rps) <= 0:
            raise ParameterError("load min_rps must be positive")
        if not isinstance(self.seed, int) or isinstance(self.seed, bool) or self.seed < 0:
            raise ParameterError("load seed must be a non-negative integer")

    def to_dict(self) -> dict[str, Any]:
        return {
            "vusers": self.vusers,
            "spawn_rate": self.spawn_rate,
            "duration_s": self.duration_s,
            "host": self.host,
            "endpoints": [endpoint.to_dict() for endpoint in self.endpoints],
            "min_rps": self.min_rps,
            "seed": self.seed,
        }


def build_load_profile(
    app: TestApplication,
    *,
    seed: int,
    duration_s: int,
) -> LoadProfile:
    """Derive a deterministic load profile for one run."""

    if duration_s < 1:
        raise ParameterError("load duration_s must be positive")
    rng = random.Random(seed ^ 0x5EED)
    vusers = rng.randint(10, 50)
    spawn_rate = rng.choice((1, 2, 5, 10))
    min_rps = max(DEFAULT_MIN_RPS, round(vusers * 0.2, 1))
    endpoints = tuple(
        LoadEndpoint(path=endpoint.path, weight=endpoint.weight, service=endpoint.service)
        for endpoint in app.load_endpoints
    )
    return LoadProfile(
        vusers=vusers,
        spawn_rate=float(spawn_rate),
        duration_s=duration_s,
        host=app.load_host,
        endpoints=endpoints,
        min_rps=min_rps,
        seed=seed,
    )


def _task_name(endpoint: LoadEndpoint) -> str:
    raw = f"{endpoint.service}_{endpoint.path.strip('/') or 'root'}"
    name = re.sub(r"[^a-z0-9]+", "_", raw.lower()).strip("_")
    if not name:
        name = "request"
    if name[0].isdigit():
        name = f"request_{name}"
    return name


def render_locustfile(profile: LoadProfile) -> str:
    """Render a deterministic Locust user class for *profile*."""

    lines = [
        '"""Generated by SPEC-30; do not edit by hand.',
        "",
        "Load profile: " + f"{profile.vusers} users, spawn {profile.spawn_rate:g}/s, "
        f"{profile.duration_s}s, min_rps={profile.min_rps:g}",
        '"""',
        "",
        "from locust import HttpUser, between, task",
        "",
        "",
        "class AutopilotFaultLoad(HttpUser):",
        "    wait_time = between(0.1, 0.5)",
        "",
    ]
    names: set[str] = set()
    for endpoint in profile.endpoints:
        name = _task_name(endpoint)
        candidate = name
        index = 2
        while candidate in names:
            candidate = f"{name}_{index}"
            index += 1
        names.add(candidate)
        lines.extend(
            [
                f"    @task({endpoint.weight})",
                f"    def {candidate}(self):",
                f"        self.client.get({endpoint.path!r})",
                "",
            ]
        )
    return "\n".join(lines).rstrip() + "\n"
